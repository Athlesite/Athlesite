// Turns a page file saved from the Studio (File › Save to a file) into a homepage example.
//   node tools/add-example.js <page.athlesite.json> [slug]
//   node tools/add-example.js --rebuild            (only rebuild examples/examples.js)
//
// - Photos inside the file (data URLs) become real files in assets/img/examples/<slug>-*.webp|jpg|png
//   and the page points at them, so the example stays small and photos load like any image.
// - The page is kept as examples/<slug>.json (the source of truth; open it in the Studio with
//   studio.html?ex=<slug>, change it, save, and run this again to update it).
// - examples/examples.js is rebuilt from every examples/*.json. Pages load that one script
//   (site.html?ex=<slug>, cards.html, studio.html?ex=<slug>, later the homepage), because pages
//   opened as files can't fetch JSON.
// Same file in again = the example is replaced (its old photo files are removed first).
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const EX = path.join(ROOT, 'examples'), IMG = path.join(ROOT, 'assets', 'img', 'examples');
const DATA_URL = /^data:image\/(webp|jpeg|png);base64,([A-Za-z0-9+/=\s]+)$/;
const EXT = { webp: 'webp', jpeg: 'jpg', png: 'png' };

const slugify = (s) => String(s || '').toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function rebuild() {
  fs.mkdirSync(EX, { recursive: true });
  const files = fs.readdirSync(EX).filter((f) => f.endsWith('.json')).sort();
  const all = {};
  for (const f of files) all[f.replace(/\.json$/, '')] = JSON.parse(fs.readFileSync(path.join(EX, f), 'utf8'));
  // "</" can't appear inside a script, whatever an example's text says.
  const body = JSON.stringify(all, null, 1).replace(/</g, '\\u003c');
  fs.writeFileSync(path.join(EX, 'examples.js'), `/* Generated by tools/add-example.js from examples/*.json. Don't edit by hand. */\n(window.Athlesite = window.Athlesite || {}).EXAMPLES = ${body};\n`);
  console.log(`examples/examples.js: ${files.length} example${files.length === 1 ? '' : 's'}${files.length ? ' (' + files.map((f) => f.replace(/\.json$/, '')).join(', ') + ')' : ''}`);
}

function add(file, slugArg) {
  const obj = JSON.parse(fs.readFileSync(file, 'utf8'));
  const profile = obj && obj.athlesite === 'page' ? obj.profile : obj && obj.data && obj.design ? obj : null;
  if (!profile || !profile.data) throw new Error('not a page file: ' + file);
  const d = profile.data;
  const slug = slugify(slugArg || `${d.firstName || ''} ${d.lastName || ''}`);
  if (!slug) throw new Error('no name in the page and no slug given');

  fs.mkdirSync(IMG, { recursive: true });
  for (const f of fs.readdirSync(IMG)) if (f.startsWith(slug + '-')) fs.unlinkSync(path.join(IMG, f));
  let written = 0, dropped = 0;
  const photo = (v, name) => {
    if (typeof v !== 'string' || !v.startsWith('data:')) return v; // links stay links
    const m = DATA_URL.exec(v);
    if (!m) { dropped++; return ''; }
    const out = `${slug}-${name}.${EXT[m[1]]}`;
    fs.writeFileSync(path.join(IMG, out), Buffer.from(m[2].replace(/\s+/g, ''), 'base64'));
    written++;
    return `assets/img/examples/${out}`;
  };
  d.heroPhotoUrl = photo(d.heroPhotoUrl, 'cover');
  (d.gallery || []).forEach((g, i) => { if (g) g.src = photo(g.src, `photo-${i + 1}`); });
  (d.highlightLinks || []).forEach((x, i) => { if (x && x.poster) x.poster = photo(x.poster, `film-${i + 1}`); });

  fs.mkdirSync(EX, { recursive: true });
  fs.writeFileSync(path.join(EX, slug + '.json'), JSON.stringify(profile, null, 2) + '\n');
  console.log(`examples/${slug}.json written; ${written} photo${written === 1 ? '' : 's'} to assets/img/examples/${dropped ? `; ${dropped} unreadable photo(s) left out` : ''}`);
  rebuild();
}

module.exports = { rebuild }; // tools/add-photos.js rebuilds examples.js the same way

if (require.main === module) {
  const [arg, slug] = process.argv.slice(2);
  if (!arg) { console.log('usage: node tools/add-example.js <page.athlesite.json> [slug] | --rebuild'); process.exit(1); }
  if (arg === '--rebuild') rebuild(); else add(path.resolve(arg), slug);
}
